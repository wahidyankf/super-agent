package domain

// PublicErrors returns the sentinel errors whose fixed texts may reach a person or a model. Every inbound adapter
// shows these texts and no other. An error outside this list gets a generic text, because its raw text can carry
// upstream detail or a local path. A new sentinel that a caller may show is added here, once, for every adapter.
